export type Key = keyof (typeof STRINGS)["en"];

export function detectLang(): Lang {
  const langs = typeof navigator !== "undefined" ? navigator.languages ?? [navigator.language] : ["en"];
  for (const l of langs) if (l && l.toLowerCase().startsWith("ru")) return "ru";
  return "en";
}

export function makeT(lang: Lang) {
  return (key: Key | string): string => {
    const table = STRINGS[lang] as Record<string, string>;
    return table[key] ?? (STRINGS.en as Record<string, string>)[key] ?? String(key);
  };
}
